#!/usr/bin/env python3
"""Wrap the game fragment (default /home/claude/ezventure.html) into index.html and stamp a new build id."""
import re,sys,time,json
src=sys.argv[1] if len(sys.argv)>1 else '/home/claude/ezventure.html'
old=open('index.html',encoding='utf-8').read()
i=old.index('<title>');j=old.index("<script>if('serviceWorker'")
head,foot=old[:i],old[j:]
build=time.strftime('%Y%m%d-%H%M%S')
head=re.sub(r'(<meta name="ezv-build" content=")[^"]*(")',r'\g<1>'+build+r'\2',head)
frag=open(src,encoding='utf-8').read().rstrip('\n')
open('index.html','w',encoding='utf-8').write(head+frag+'\n\n'+foot)
json.dump({'build':build},open('version.json','w'))
print('build',build)

# ---- UI kit: extract the EZUI block + tokens from the game so the kit never drifts from the game ----
import os
fr=frag
m=re.search(r'/\* EZUI:START.*?/\* EZUI:END \*/',fr,re.S)
root=re.search(r':root\{.*?\n\}',fr,re.S)
fonts=re.search(r'<link rel="stylesheet" href="https://fonts[^>]*>',fr)
if m and root:
    tok=root.group(0)
    open('ui-kit/ezui.css','w',encoding='utf-8').write('/* Ezventure UI kit (auto-generated by build.py from the game source — edit the game, not this file) */\n'+tok+'\n*{box-sizing:border-box}\nbody{margin:0;font-family:var(--f-body);color:var(--ink)}\nh2,h3{font-family:var(--f-display);margin:0}\n[hidden]{display:none!important}\n'+m.group(0)+'\n')
    if fonts: open('ui-kit/fonts.html','w').write(fonts.group(0)+'\n')
    print('ui-kit css ok')
